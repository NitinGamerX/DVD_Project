"""Single-transistor simulations for the four cases (Part A, step 1).

Batch path (used for the datasets): one ngspice process per chunk of samples.
The model card is the parametrised copy (model/derived/22nm_MGK_param.pm);
each sample is applied with `alterparam` + `reset` + `op`.

Literal path (used for verification): one ngspice process per sample, with the
sample's numbers written directly into a private copy of the model card and the
device line. It shares no parameter machinery with the batch path, so agreement
between the two is an independent check of the batch results.

Currents are ngspice source branch currents I(Vd), I(Vg), I(Vs), I(Vb):
positive = current flowing out of the device terminal into its source
(the convention of the example netlist and the slides' sample database).
"""
from __future__ import annotations

import os
import re
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

from . import config, modelcard, netlist, spice

PARAM_MODEL = Path("model", "derived", "22nm_MGK_param.pm")
CURRENTS = ["id", "ig", "is", "ib"]
_SAMPLE_RE = re.compile(r"^@@ (\d+)\s*$")
_VAL_RE = re.compile(r"^v([dgsb])#branch = (\S+)\s*$")


def _process_names() -> list[str]:
    return config.load()["sweep"]["process_params"]


def write_param_model() -> Path:
    """(Re)generate the parametrised model card from the original file."""
    out = config.path(*PARAM_MODEL.parts)
    out.parent.mkdir(parents=True, exist_ok=True)
    body = modelcard.render(config.model_file(), _process_names())
    out.write_text(
        "* GENERATED by src/dvd/fetsim.py from model/22nm_MGK.pm -- do not edit.\n"
        "* Identical to the original except: vth0, toxe, ndep, u0, xj are SPICE\n"
        "* parameters ({name_n} in the nmos card, {name_p} in the pmos card).\n"
        + body)
    return out


def n_jobs() -> int:
    j = config.load()["spice"]["n_jobs"]
    if j in (-1, None):
        return os.cpu_count() or 1
    return max(1, int(j))


def _model_name(case: str) -> str:
    cfg = config.load()
    return cfg["assignment"]["nmos_model" if cfg["cases"][case]["type"] == "n" else "pmos_model"]


def _param_header(include: str, values: dict[str, dict[str, float]]) -> list[str]:
    cfg = config.load()
    lines = [".param " + " ".join(f"{p}_{t}={repr(float(values[t][p]))}" for p in _process_names())
             for t in ("n", "p")]
    return lines + [f".include {include}", cfg["spice"]["options"]]


def _batch_deck(case: str, chunk: pd.DataFrame, start: int, include: str) -> str:
    """One deck that simulates every row of `chunk` in turn."""
    t = config.load()["cases"][case]["type"]
    from .sampling import process_nominals
    lines = [f"* batch: case {case}, samples {start}..{start + len(chunk) - 1}"]
    lines += _param_header(include, process_nominals())
    lines += [".param tc=27 w=44n vdv=0 vgv=0 vsv=0 vbv=0", ".temp {tc}",
              netlist.mos_line_expr("M1", "d", "g", "s", "b", _model_name(case)),
              "Vd d 0 {vdv}", "Vg g 0 {vgv}", "Vs s 0 {vsv}", "Vb b 0 {vbv}",
              ".control", "set numdgt=15"]
    for k, r in enumerate(chunk.itertuples(index=False)):
        sets = dict(tc=r.temp, w=r.w, vdv=r.vd, vgv=r.vg, vsv=r.vs, vbv=r.vb)
        sets.update({f"{p}_{t}": getattr(r, p) for p in _process_names()})
        lines += [f"alterparam {k_}={repr(float(v))}" for k_, v in sets.items()]
        lines += ["reset", "op", f"echo @@ {start + k}",
                  "print vd#branch vg#branch vs#branch vb#branch", "destroy all"]
    lines += [".endc", ".end", ""]
    return "\n".join(lines)


def _parse_batch(stdout: str, start: int, n: int) -> np.ndarray:
    out = np.full((n, 4), np.nan)
    idx = None
    order = "dgsb"
    for line in stdout.splitlines():
        m = _SAMPLE_RE.match(line)
        if m:
            idx = int(m.group(1)) - start
            continue
        m = _VAL_RE.match(line)
        if m and idx is not None:
            out[idx, order.index(m.group(1))] = float(m.group(2))
    return out


def simulate(case: str, inputs: pd.DataFrame, chunk_size: int = 500,
             jobs: int | None = None) -> np.ndarray:
    """Terminal currents (n, 4) = I(Vd), I(Vg), I(Vs), I(Vb) for every input row."""
    work = config.path("work", "fet")
    work.mkdir(parents=True, exist_ok=True)
    include = os.path.relpath(config.path(*PARAM_MODEL.parts), work)
    starts = list(range(0, len(inputs), chunk_size))

    def run(start: int) -> tuple[int, np.ndarray]:
        chunk = inputs.iloc[start:start + chunk_size]
        out = spice.run_deck(_batch_deck(case, chunk, start, include), work)
        return start, _parse_batch(out, start, len(chunk))

    result = np.full((len(inputs), 4), np.nan)
    with ThreadPoolExecutor(max_workers=jobs or n_jobs()) as ex:
        for start, block in ex.map(run, starts):
            result[start:start + len(block)] = block
    missing = np.flatnonzero(np.isnan(result).any(axis=1))
    if missing.size:
        raise spice.SpiceError(f"{case}: no result for {missing.size} samples, e.g. {missing[:10].tolist()}")
    return result


def literal_deck(case: str, row: pd.Series, model_include: str) -> str:
    """Stand-alone deck for one sample with every number written literally."""
    cfg = config.load()
    return "\n".join([
        f"* literal check: case {case}",
        f".include {model_include}",
        cfg["spice"]["options"],
        f".temp {repr(float(row.temp))}",
        netlist.mos_line("M1", "d", "g", "s", "b", _model_name(case), float(row.w)),
        f"Vd d 0 {repr(float(row.vd))}", f"Vg g 0 {repr(float(row.vg))}",
        f"Vs s 0 {repr(float(row.vs))}", f"Vb b 0 {repr(float(row.vb))}",
        ".control", "set numdgt=15", "op", "print vd#branch vg#branch vs#branch vb#branch",
        ".endc", ".end", ""])


def simulate_literal(case: str, row: pd.Series) -> np.ndarray:
    """Simulate one sample through the literal path (fresh model card, fresh process)."""
    from .sampling import process_nominals
    t = config.load()["cases"][case]["type"]
    values = process_nominals()
    values[t] = {p: float(row[p]) for p in _process_names()}
    work = config.path("work", "fet_literal")
    work.mkdir(parents=True, exist_ok=True)
    card = work / f"card_{case}_{os.getpid()}_{row.name}.pm"
    card.write_text(modelcard.render(config.model_file(), _process_names(), values))
    try:
        out = spice.run_deck(literal_deck(case, row, card.name), work)
    finally:
        card.unlink(missing_ok=True)
    v = spice.printed(out)
    return np.array([v[f"v{x}#branch"] for x in "dgsb"])


def example_deck(case: str, row: pd.Series, sample_index: int) -> str:
    """Readable stand-alone netlist reproducing one dataset sample (deliverable 2).

    Run from netlists/single_fet/:  ngspice -b <case>.cir
    """
    cfg = config.load()
    from .sampling import process_nominals
    t = cfg["cases"][case]["type"]
    values = process_nominals()
    values[t] = {p: float(row[p]) for p in _process_names()}
    include = os.path.relpath(config.path(*PARAM_MODEL.parts), config.path("netlists", "single_fet"))
    spec = cfg["cases"][case]
    lines = [
        f"* Single-transistor netlist, case {case.upper()} (Vg={spec['vg']}, Vb={spec['vb']})",
        f"* Reproduces sample {sample_index} of data/fet/{case}.csv",
        "* Every terminal has its own voltage source; source/drain areas included.",
        "* Process parameters (both device types defined; this case uses the "
        f"{'NMOS' if t == 'n' else 'PMOS'} set):",
        *_param_header(include, values),
        f".temp {repr(float(row.temp))}",
        f"* VDD = {repr(float(row.vdd))} V",
        netlist.mos_line("M1", "d", "g", "s", "b", _model_name(case), float(row.w)),
        f"Vd d 0 {repr(float(row.vd))}", f"Vg g 0 {repr(float(row.vg))}",
        f"Vs s 0 {repr(float(row.vs))}", f"Vb b 0 {repr(float(row.vb))}",
        ".control", "set numdgt=15", "op", "print i(vd) i(vg) i(vs) i(vb)",
        ".endc", ".end", ""]
    return "\n".join(lines)
